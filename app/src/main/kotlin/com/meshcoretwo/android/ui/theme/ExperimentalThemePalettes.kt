// Full Material3 ColorScheme for each experimental theme (see `Theme.Experimental`). Original
// palettes, no third-party color set. Generated offline the same way as `ThemePalettes.kt` —
// Material color-utilities "Fidelity", contrast level 0, spec "2021", seeded from the theme's light
// or dark accent, computed with the `materialyoucolor` Python port — with two overrides on every
// adaptive theme: `background`/`surface` are the theme's canvas (as in `ThemePalettes.kt`), and
// `primary` is the accent itself (white `onPrimary` in light, black in dark), so bubbles and the
// selected tab carry the theme's signature color rather than Fidelity's deeper/paler tone.
//
// Hand-tuned exceptions:
// - Night: every role is red-only on black (preserves dark adaptation), not generated.
// - Phosphor: every role hand-picked green-on-black (terminal phosphor), amber tertiary.
// - Daylight: Fidelity at contrast level 1.0 (high contrast), pure white canvas, black text.
// - Mesh dark: surface containers tinted navy to sit on the navy canvas.
// - Blueprint dark: canvas is blueprint blue, so surface containers, text, outlines and the
//   secondary container are blue-tinted by hand.
// - Neon: every role hand-picked — magenta on purple night, cyan secondary, yellow tertiary.
// - Hazard light: primary is black with safety-yellow content (yellow itself is unreadable as text
//   on a light canvas); yellow lives in the container, the outgoing bubble and the pattern. Dark:
//   neutral greys under a yellow primary.
// - Notebook dark (chalkboard), Newsprint (both), Starmap dark (night sky): surfaces, text and
//   outlines set by hand to the canvas's tint; Newsprint is neutral rather than red-tinted.
// - Starmap: `primaryContainer` is tonal (pale lavender / deep gold) instead of the accent itself,
//   so selected chips and settings tiles don't read as heavy solid blocks.
// - Labels on containers (`onPrimaryContainer`/`onSecondaryContainer`/`onTertiaryContainer`/
//   `onErrorContainer`), every theme: Fidelity leaves them at ~4.5:1 in the container's own hue, so
//   the text on chips, FABs and tonal buttons looked tinted the same as the button. Hue and chroma
//   are kept, the tone is pushed away from the container to 7:1 (or to white/black where a
//   saturated mid-tone container can't reach 7:1 with any tint).
// Forced-appearance themes (Night, Phosphor, Neon dark-only; Daylight light-only) ship one scheme.
// `RedesignContrastTest`/`ThemeContrastTest` guard the AA pairs.

